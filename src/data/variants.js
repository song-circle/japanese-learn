// 원래 목소리(Nanami·Keita)와 다른 목소리들
const FEMALE = ['ja-JP-AoiNeural', 'ja-JP-MayuNeural', 'ja-JP-ShioriNeural']
const MALE = ['ja-JP-DaichiNeural', 'ja-JP-NaokiNeural']
const MALE_ROLES = ['기사']
const hash = (str) => [...str].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7)
function voiceFor(key, who) {
  const pool = MALE_ROLES.includes(who) ? MALE : hash(key) % 3 === 0 ? MALE : FEMALE
  return pool[hash(`${key}#voice`) % pool.length]
}

// 점원·상대 문장(내가 하는 말 제외)
const others = allSentences.filter((s) => s.who !== '나')

// 음성 만들기·문제 내기용 목록
//   텍스트 다른 표현: { id: 'var-<문장>-<n>', sid, ja, kana, pron, voice }
//   같은 문장 다른 목소리: { id: 'voice-<문장>', sid, ja(=원문), tts, voice }
export const variantClips = Object.entries(variants).flatMap(([sid, list]) => {
  const s = allSentences.find((x) => x.id === sid)
  return list.map(([ja, kana, pron], i) => ({
    id: `var-${sid}-${i + 1}`, sid, ja, kana, pron: tense(pron), voice: voiceFor(`${sid}-${i}`, s?.who),
  }))
})
export const voiceClips = others.map((s) => ({
  id: `voice-${s.id}`, sid: s.id, ja: s.ja, tts: s.tts ?? s.ja, voice: voiceFor(`voice-${s.id}`, s.who),
}))
