// 틀 발음도 문장과 같은 된소리 규칙으로(〜와 도코 데스카 → 〜와 도꼬 데스까)
for (const p of patterns) p.pron = tense(p.pron)

// 패턴 문장 전체(말하기 채점·음성 만들기용). 말하는 사람은 모두 '나'
export const patternSentences = patterns.flatMap((p) =>
  p.words.map((x) => {
    const m = p.make(x)
    return {
      id: `pat-${p.id}-${x.id}`,
      pattern: p.id,
      who: '나',
      ja: m.ja,
      // 음성 합성에 넘길 글(영어 표기는 가타카나로 읽게)
      ...(m.ja.includes('Wi-Fi') ? { tts: m.ja.replace('Wi-Fi', 'ワイファイ') } : {}),
      kana: m.kana,
      pron: tense(m.pron),
      ko: m.ko,
      word: { ja: x.ja, pron: tense(x.pron), ko: x.ko },
      words: [[x.ja, tense(x.pron), x.ko]],
    }
  }),
)
